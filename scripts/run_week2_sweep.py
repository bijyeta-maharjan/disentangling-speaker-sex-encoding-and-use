"""Week-2 multi-architecture / multi-seed training sweep (runs in background).

Priority phases (Discipline E — one complete cross-architecture pass first):
  core_si_seed42      CORE archs, SI split, seed 42   (needed first by the probing scripts)
  core_si_extra_seeds CORE archs, SI split, seeds 43 & 44
  core_sd_seed42      CORE archs, SD split, seed 42    (per-arch leakage gap, H5)
  stretch_si_seed42   STRETCH archs, SI split, seed 42 (only if core finishes)

Each job trains under the SHARED fixed protocol (config week2_architectures.yaml),
checkpoints + per-epoch logs land in their own experiments/ run dir, and a result
row is appended to experiments/week2_sweep/results.jsonl. The per-architecture
table (results/training/arch_table.md) is regenerated after EVERY completed job, so
it fills in live as runs finish.

    python scripts/run_week2_sweep.py --phases core_si_seed42 [...]
"""
import argparse
import json
import sys
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import torch

from src.data.dataset import AudioMNISTCacheDataset
from src.data.preprocess import load_cache
from src.models.factory import CORE_ARCHS, STRETCH_ARCHS, build_model, input_kind
from src.splits.make_splits import load_split_indices
from src.train.trainer import train
from src.utils.config import load_config, paths, resolve, resolve_arch_cfg

REPO = Path(__file__).resolve().parents[1]
WEEK2 = REPO / "configs" / "week2_architectures.yaml"
SWEEP_DIR = resolve("experiments/week2_sweep")
RESULTS = SWEEP_DIR / "results.jsonl"
TABLE = resolve("results/training/arch_table.md")

PHASES = {
    "core_si_seed42": [(a, "speaker_independent", 42) for a in CORE_ARCHS],
    "core_si_extra_seeds": [(a, "speaker_independent", s) for s in (43, 44) for a in CORE_ARCHS],
    "core_sd_seed42": [(a, "speaker_dependent", 42) for a in CORE_ARCHS],
    "stretch_si_seed42": [(a, "speaker_independent", 42) for a in STRETCH_ARCHS],
}


@torch.no_grad()
def test_accuracy(cfg: dict, regime: str, run_dir: Path) -> float:
    """Overall test-set accuracy for a finished run (lightweight; no figs/bootstrap)."""
    ckpt = torch.load(run_dir / "best.pt", map_location="cpu", weights_only=False)
    model = build_model(cfg)
    model.load_state_dict(ckpt["model_state"])
    model.eval()

    feature = input_kind(cfg)
    cache = load_cache(cfg)
    if feature == "spectrogram":
        from src.data.spectrogram import load_spec_cache

        cache["spec"] = load_spec_cache(cfg)["spec"]
    test_idx = load_split_indices(cfg, regime, cache)["test"]
    ds = AudioMNISTCacheDataset(cache, test_idx, feature=feature)
    loader = torch.utils.data.DataLoader(ds, batch_size=cfg["train"]["batch_size"], shuffle=False)
    correct = total = 0
    for x, y, _ in loader:
        correct += (model(x).argmax(1) == y).sum().item()
        total += len(y)
    return correct / total


def run_job(base_cfg: dict, arch: str, regime: str, seed: int) -> dict:
    cfg = resolve_arch_cfg(base_cfg, arch=arch, seed=seed)
    print(f"\n===== SWEEP JOB: arch={arch} regime={regime} seed={seed} =====")
    t0 = time.perf_counter()
    summary = train(cfg, regime)
    acc = test_accuracy(cfg, regime, Path(summary["run_dir"]))
    rec = {
        "arch": arch,
        "regime": regime,
        "seed": seed,
        "n_params": summary["n_params"],
        "input": summary["input"],
        "best_val_acc": round(summary["best_val_acc"], 5),
        "test_acc": round(acc, 5),
        "epochs_to_stop": summary["epochs_to_stop"],
        "best_epoch": summary["best_epoch"],
        "wall_s": round(time.perf_counter() - t0, 1),
        "run_dir": summary["run_dir"],
        "git_sha": summary["git_sha"],
        "finished": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }
    SWEEP_DIR.mkdir(parents=True, exist_ok=True)
    with open(RESULTS, "a", encoding="utf-8") as fh:
        fh.write(json.dumps(rec) + "\n")
    print(f"[sweep] {arch}/{regime}/seed{seed}: test_acc={acc:.4f} "
          f"epochs_to_stop={rec['epochs_to_stop']} wall={rec['wall_s']}s")
    build_table()
    return rec


def _load_results() -> list[dict]:
    if not RESULTS.exists():
        return []
    with open(RESULTS, "r", encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def build_table() -> None:
    """Regenerate results/training/arch_table.md from results.jsonl."""
    rows = _load_results()
    by_key = {}  # keep the LATEST record per (arch, regime, seed)
    for r in rows:
        by_key[(r["arch"], r["regime"], r["seed"])] = r

    archs = [a for a in CORE_ARCHS + STRETCH_ARCHS if any(k[0] == a for k in by_key)]
    lines = [
        "# Week-2 architecture comparison table",
        "",
        f"_Auto-generated by scripts/run_week2_sweep.py — last update "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}._",
        "",
        "Independent variable: **architecture**. All else held fixed (identical "
        "preprocessing, reused Week-1 SI/SD splits, shared Adam protocol, CPU). "
        "Capacity (param count) and epochs-to-stop are reported covariates. SD "
        "test accuracy is memorization-inflated by design; the leakage gap "
        "(SD − SI) is the diagnostic, not a ranking.",
        "",
        "| arch | scope | input | params | seed | SI test acc | SD test acc | leakage gap (SD−SI) | SI epochs→stop |",
        "|------|------|-------|-------:|-----:|------------:|------------:|--------------------:|---------------:|",
    ]
    for arch in archs:
        scope = "core" if arch in CORE_ARCHS else "stretch"
        seeds = sorted({k[2] for k in by_key if k[0] == arch})
        for seed in seeds:
            si = by_key.get((arch, "speaker_independent", seed))
            sd = by_key.get((arch, "speaker_dependent", seed))
            params = (si or sd)["n_params"]
            inp = (si or sd)["input"]
            si_acc = f"{si['test_acc']:.4f}" if si else "—"
            sd_acc = f"{sd['test_acc']:.4f}" if sd else "—"
            gap = f"{sd['test_acc'] - si['test_acc']:+.4f}" if (si and sd) else "—"
            ep = str(si["epochs_to_stop"]) if si else "—"
            lines.append(f"| {arch} | {scope} | {inp} | {params:,} | {seed} | {si_acc} | {sd_acc} | {gap} | {ep} |")

    # multi-seed SI mean per arch (the primary cross-architecture comparison)
    lines += ["", "## SI test accuracy across seeds (primary comparison)", "",
              "| arch | seeds | SI acc mean | SI acc per-seed |",
              "|------|-------|------------:|-----------------|"]
    for arch in archs:
        si_runs = [by_key[k] for k in by_key if k[0] == arch and k[1] == "speaker_independent"]
        if not si_runs:
            continue
        accs = sorted((r["seed"], r["test_acc"]) for r in si_runs)
        mean = float(np.mean([a for _, a in accs]))
        per = ", ".join(f"s{s}:{a:.4f}" for s, a in accs)
        lines.append(f"| {arch} | {len(accs)} | {mean:.4f} | {per} |")

    lines += ["", f"_Completed jobs: {len(by_key)}._", ""]
    TABLE.parent.mkdir(parents=True, exist_ok=True)
    TABLE.write_text("\n".join(lines), encoding="utf-8")
    print(f"[sweep] table -> {TABLE} ({len(by_key)} jobs)")


def main():
    ap = argparse.ArgumentParser(description="Run the Week-2 architecture sweep.")
    ap.add_argument("--phases", nargs="+", default=["core_si_seed42"],
                    choices=list(PHASES) + ["all"],
                    help="which priority phases to run, in order")
    ap.add_argument("--table-only", action="store_true", help="just rebuild the table and exit")
    args = ap.parse_args()

    if args.table_only:
        build_table()
        return

    phases = list(PHASES) if "all" in args.phases else args.phases
    jobs = [job for ph in phases for job in PHASES[ph]]
    print(f"[sweep] phases={phases} -> {len(jobs)} jobs")

    base = load_config(WEEK2)
    done = {(r["arch"], r["regime"], r["seed"]) for r in _load_results()}
    for arch, regime, seed in jobs:
        if (arch, regime, seed) in done:
            print(f"[sweep] skip already-done {arch}/{regime}/seed{seed}")
            continue
        run_job(base, arch, regime, seed)
    print("[sweep] all requested jobs complete.")


if __name__ == "__main__":
    main()
